/** Preferred display order; any value not listed keeps data order after these. */
const THEME_ORDER = ["転職", "若手・第二新卒", "管理職・リーダー", "ワークライフ・復職", "セカンドキャリア"];
const AREA_ORDER = ["東京", "大阪", "名古屋", "福岡", "オンライン全国"];
const FORMAT_ORDER = ["オンライン", "対面"];
const TYPE_ORDER = ["独立・個人", "企業所属"];

function unique(values: string[]): string[] {
  return Array.from(new Set(values));
}

function ordered(values: string[], order: string[]): string[] {
  const uniq = unique(values);
  const rank = (v: string) => {
    const i = order.indexOf(v);
    return i === -1 ? order.length : i;
  };
  return uniq
    .map((v, i) => ({ v, i }))
    .sort((a, b) => rank(a.v) - rank(b.v) || a.i - b.i)
    .map((x) => x.v);
}

export const THEMES = ordered(ADVISORS.map((a) => a.theme), THEME_ORDER);
export const AREAS = ordered(ADVISORS.map((a) => a.area), AREA_ORDER);
export const FORMATS = ordered(
  ADVISORS.flatMap((a) => a.format.split("／")),
  FORMAT_ORDER,
);
export const TYPES = ordered(ADVISORS.map((a) => a.type), TYPE_ORDER);

/* ---------- filtering ---------- */

export type SortKey = "rec" | "years" | "name";

export type Filters = {
  theme: string;
  area: string;
  format: string;
  type: string;
  sort: SortKey;
  keyword: string;
};

export const EMPTY_FILTERS: Filters = {
  theme: "",
  area: "",
  format: "",
  type: "",
  sort: "rec",
  keyword: "",
};

export function filterAdvisors(f: Filters): Advisor[] {
  const kw = f.keyword.trim();
  const list = ADVISORS.filter((a) => {
    if (f.theme && a.theme !== f.theme) return false;
    if (f.area && a.area !== f.area) return false;
    if (f.format && !a.format.includes(f.format)) return false;
    if (f.type && a.type !== f.type) return false;
    if (kw) {
      const hay = a.name + a.kana + a.thought + a.theme + a.area + a.lead;
      if (!hay.includes(kw)) return false;
    }
    return true;
  });
  if (f.sort === "years") return list.slice().sort((x, y) => y.years - x.years);
  if (f.sort === "name") return list.slice().sort((x, y) => x.kana.localeCompare(y.kana, "ja"));
  return list;
}

export function getAdvisor(id: number): Advisor | undefined {
  return ADVISORS.find((a) => a.id === id);
}
